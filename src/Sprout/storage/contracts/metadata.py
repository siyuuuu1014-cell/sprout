"""Metadata store contract for the SEMA control layer."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Protocol

from Sprout.artifacts.models import Artifact
from Sprout.execution.models import ChangeProposal
from Sprout.task.models import Task, TaskStatus
from Sprout.trajectory.models import Trajectory
from Sprout.workspace.models import Workspace

if TYPE_CHECKING:
    from Sprout.execution.node_result_source import NodeResultSourceV1
    from Sprout.orchestration.models import ExecutionNode


class MetadataStore(Protocol):
    """Persists structured control-layer objects.

    Raw events and large blobs do not belong here. EventStore and BlobStore
    own those responsibilities.
    """

    async def save_workspace(self, workspace: Workspace) -> None: ...
    async def get_workspace(self, workspace_id: str) -> Workspace | None: ...
    async def list_workspaces(self) -> list[Workspace]: ...

    async def save_task(self, task: Task) -> None: ...
    async def get_task(self, task_id: str) -> Task | None: ...
    async def list_tasks(self, workspace_id: str | None = None) -> list[Task]: ...
    async def update_task_status(self, task_id: str, status: TaskStatus) -> None: ...
    async def ensure_task_submission(self, record: dict[str, Any]) -> dict[str, Any]: ...
    async def update_task_submission(self, record: dict[str, Any]) -> None: ...
    async def list_task_submissions(self, task_id: str) -> list[dict[str, Any]]: ...
    async def reserve_model_request(self, task_id: str, node_id: str, limit: int) -> str | None: ...
    async def finish_model_request(self, request_id: str, state: str, usage: dict) -> bool: ...
    async def model_budget_summary(self, task_id: str) -> dict: ...
    async def get_replay_resume(self, task_id: str) -> dict[str, Any] | None: ...
    async def claim_replay_resume(self, record: dict[str, Any]) -> bool: ...
    async def finish_replay_resume(
        self, task_id: str, owner: str, state: str, result: dict[str, Any]
    ) -> bool: ...
    async def get_verification_execution(self, execution_id: str) -> dict[str, Any] | None: ...
    async def get_coding_execution(self, execution_id: str) -> dict[str, Any] | None: ...
    async def get_coding_intent(self, intent_id: str) -> dict[str, Any] | None: ...
    async def ensure_coding_intent(self, record: dict[str, Any]) -> dict[str, Any]: ...
    async def claim_coding_execution(self, record: dict[str, Any]) -> bool: ...
    async def finish_coding_execution(
        self, execution_id: str, owner: str, state: str, result: dict[str, Any]
    ) -> bool: ...
    async def claim_verification_execution(self, record: dict[str, Any]) -> bool: ...
    async def finish_verification_execution(
        self, execution_id: str, owner: str, state: str, result: dict[str, Any]
    ) -> bool: ...

    async def save_execution_node(self, node: ExecutionNode) -> None: ...
    async def get_execution_node(self, node_id: str) -> ExecutionNode | None: ...
    async def list_execution_nodes(self, task_id: str) -> list[ExecutionNode]: ...
    async def claim_execution_node(
        self, node: ExecutionNode, owner: str, resume_key: str
    ) -> bool: ...
    async def finish_execution_node(self, node: ExecutionNode, owner: str, state: str) -> bool: ...

    async def save_node_result_source(self, source: NodeResultSourceV1) -> bool: ...
    async def get_node_result_source(self, node_id: str) -> NodeResultSourceV1 | None: ...

    async def save_artifact(self, artifact: Artifact) -> None: ...
    async def record_artifact_validation(
        self, artifact: Artifact, record: dict[str, Any]
    ) -> bool: ...
    async def claim_artifact_publication(
        self, artifact: Artifact, owner: str, decided_by: str = ""
    ) -> bool: ...
    async def finish_artifact_publication(
        self, artifact: Artifact, owner: str, state: str
    ) -> bool: ...
    async def get_artifact(self, artifact_id: str) -> Artifact | None: ...
    async def list_artifacts(self, name: str | None = None) -> list[Artifact]: ...

    async def save_change_proposal(self, proposal: ChangeProposal) -> None: ...
    async def get_git_proposal_snapshot(self, proposal_id: str) -> dict[str, Any] | None: ...
    async def get_git_transaction(self, transaction_id: str) -> dict[str, Any] | None: ...
    async def approve_apply_proposal(self, snapshot: dict[str, Any]) -> bool: ...
    async def claim_apply_transaction(
        self, record: dict[str, Any], snapshot: dict[str, Any]
    ) -> bool: ...
    async def get_apply_transaction(self, identifier: str) -> dict[str, Any] | None: ...
    async def update_apply_transaction(
        self, identifier: str, owner: str, **change: Any
    ) -> bool: ...
    async def begin_git_commit_write(self, transaction_id: str, owner: str) -> bool: ...
    async def activate_commit_task(self, task_id: str, replay_fingerprint: str) -> bool: ...
    async def complete_isolated_commit_task(
        self, task_id: str, request_id: str, request_fingerprint: str, evaluation_node_id: str,
    ) -> bool: ...
    async def settle_git_commit_proposal(
        self, transaction_id: str, owner: str, result: dict[str, Any]
    ) -> bool: ...
    async def claim_git_transaction(
        self, record: dict[str, Any], snapshot: dict[str, Any]
    ) -> bool: ...
    async def finish_git_transaction(
        self, transaction_id: str, owner: str, state: str, result: dict[str, Any]
    ) -> bool: ...
    async def get_change_proposal(self, proposal_id: str) -> ChangeProposal | None: ...
    async def list_change_proposals(self, task_id: str) -> list[ChangeProposal]: ...

    async def save_trajectory_metadata(self, trajectory: Trajectory) -> None: ...
    async def get_trajectory_metadata(self, trajectory_id: str) -> Trajectory | None: ...
